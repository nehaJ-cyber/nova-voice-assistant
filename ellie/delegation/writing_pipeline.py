"""
Unified Qwen Writing Delegation Pipeline for Nova / Ellie.
Orchestrates Laya delegation -> Qwen generation -> Foreground Paste -> Memory Flush.
"""
import logging
import re
from typing import Dict, Any, Optional
from ellie.llm.ollama_client import OllamaClient
from ellie.automation.clipboard_injector import ClipboardInjector
from ellie.guardrails.memory_guardrail import MemoryGuardrail

logger = logging.getLogger(__name__)

SYSTEM_PROMPT_WRITER = (
    "You are an automated drafting engine. "
    "Generate ONLY the exact requested text. "
    "DO NOT include any conversational preamble, pleasantries, explanations, disclaimers, or postscript remarks. "
    "DO NOT enclose the text in markdown code blocks unless explicitly requested. "
    "Start directly with the drafted text content."
)


class WritingDelegationPipeline:
    def __init__(
        self,
        ollama_client: Optional[OllamaClient] = None,
        injector: Optional[ClipboardInjector] = None,
        guardrail: Optional[MemoryGuardrail] = None,
        model_name: str = "qwen2.5:1.5b",
        config: Optional[Dict[str, Any]] = None,
    ):
        self.config = config or {}
        if config and "models" in config:
            self.model_name = config["models"].get("executor", model_name)
            host = config["models"].get("ollama_host", "http://127.0.0.1:11434")
            self.ollama_client = ollama_client or OllamaClient(host=host, default_model=self.model_name)
            self.guardrail = guardrail or MemoryGuardrail(ollama_host=host)
        else:
            self.model_name = model_name
            self.ollama_client = ollama_client or OllamaClient(default_model=model_name)
            self.guardrail = guardrail or MemoryGuardrail()

        self.injector = injector or ClipboardInjector()

    def clean_output(self, raw_text: str) -> str:
        text = raw_text.strip()
        # Remove conversational opening if present
        text = re.sub(
            r"^(Here is|Here's|Certainly|Sure)[^\n]*[:!]\s*\n*", "", text, flags=re.IGNORECASE
        )
        text = re.sub(
            r"^(Here is|Here's|Certainly|Sure)[^\n]*:\s*\n*", "", text, flags=re.IGNORECASE
        )
        # Remove surrounding markdown fences if wrapping entire text
        if text.startswith("```") and text.endswith("```"):
            text = re.sub(r"^```[a-zA-Z0-9_-]*\n", "", text)
            text = re.sub(r"\n```$", "", text)
        return text.strip()

    def _generate_text(self, prompt: str) -> str:
        return self.ollama_client.generate(
            prompt=prompt,
            system_prompt=SYSTEM_PROMPT_WRITER,
            model=self.model_name,
            keep_alive=0,
        )

    def _paste_to_active_app(self, text: str) -> bool:
        if hasattr(self.injector, "inject_text"):
            return self.injector.inject_text(text, clear_after=True)
        return self.injector.inject_and_paste(text, clear_after=True)

    def delegate_writing(self, prompt: str, target_window_title: Optional[str] = None) -> Dict[str, Any]:
        """
        PROJECT.md Interface Contract:
        1. Formulates sanitized prompt for qwen2.5:1.5b.
        2. Queries Ollama with inline keep_alive=0.
        3. Injects text into active foreground window via ClipboardInjector.
        4. Triggers MemoryGuardrail.flush() in finally block.
        """
        result: Dict[str, Any] = {
            "success": False,
            "target_window": None,
            "generated_text": "",
            "pasted": False,
            "telemetry": {},
            "prompt": prompt,
        }

        # Step 1: Detect foreground window
        fw = self.injector.get_foreground_window()
        result["target_window"] = fw

        try:
            # Step 2: Generate text via Qwen with keep_alive=0
            raw_text = self._generate_text(prompt)
            cleaned_text = self.clean_output(raw_text)
            result["generated_text"] = cleaned_text

            # Step 3: Paste into target application
            if cleaned_text:
                pasted = self._paste_to_active_app(cleaned_text)
                result["pasted"] = pasted
                result["success"] = pasted
            else:
                logger.warning("No text generated by Qwen.")
        finally:
            # Step 4: GUARANTEED 4-Tier Memory & Process Cache Flush
            flush_report = self.guardrail.flush(ollama_client=self.ollama_client, model_name=self.model_name)
            result["telemetry"] = flush_report

        return result

    def execute_writing_task(self, prompt: str) -> Dict[str, Any]:
        """Alias for delegate_writing."""
        return self.delegate_writing(prompt)

    def process_and_paste(self, prompt: str) -> bool:
        """Convenience method returning boolean success."""
        res = self.delegate_writing(prompt)
        return bool(res.get("success", False))
